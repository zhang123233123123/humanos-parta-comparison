import type { Question } from '@/lib/contracts/simulation-contracts'

/** Explanations use question definitions and control labels, never a user's answer values. */
export function questionHelp(q: Question) {
  const format =
    q.type === 'multiple'
      ? '可以选择多项，再次点击可取消。'
      : q.type === 'single'
        ? '请选择一项，选择其他选项会替换本题原选择。'
        : q.type === 'scale' || q.type === 'number'
          ? `填写 ${q.minimum}–${q.maximum} 范围内的数值，步长为 ${q.step}。${q.low_label ? `低端：${q.low_label}。` : ''}${q.high_label ? `高端：${q.high_label}。` : ''}`
          : '用文字填写你的实际情况。'
  return `${q.help ? q.help + ' ' : ''}${format}${q.required ? '本题必填。' : '本题可选。'}填写后按页面提示保存或提交。`
}

