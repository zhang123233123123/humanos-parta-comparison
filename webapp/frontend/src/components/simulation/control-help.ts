export type ControlStep = {
  target: string
  title: string
  text: string
  documented: boolean
}
const ids = new WeakMap<Element, string>()
let serial = 0
export function visible(el: HTMLElement) {
  return (
    !!el.getClientRects().length &&
    !el.closest('[hidden],[inert],[aria-hidden="true"]') &&
    getComputedStyle(el).visibility === 'visible' &&
    getComputedStyle(el).display !== 'none'
  )
}
export function helpRoot(): HTMLElement | Document {
  return (
    Array.from(document.querySelectorAll<HTMLElement>('[data-runtime-dialog]'))
      .reverse()
      .find(visible) ||
    document.querySelector<HTMLElement>('[data-simulation-app]') ||
    document
  )
}
function labelText(el: Element | null): string {
  if (!el) return ''
  const clone = el.cloneNode(true) as Element
  clone
    .querySelectorAll('input,select,textarea,button,svg,[role="alert"]')
    .forEach((x) => x.remove())
  return (clone.textContent || '')
    .replace(/\s+/g, ' ')
    .replace(/\s*\*$/, '')
    .trim()
}
export function controlSteps(): ControlStep[] {
  return Array.from(
    helpRoot().querySelectorAll<HTMLElement>(
      'button,a[href],input:not([type="hidden"]),select,textarea,summary,[role="button"],.fc-event:not(.fc-bg-event)',
    ),
  )
    .filter(
      (el) =>
        visible(el) &&
        !el.closest('[data-simulation-tour]') &&
        !/操作引导|新手指引|Workspace guide/.test(
          el.getAttribute('aria-label') || el.textContent || '',
        ),
    )
    .map((el) => {
      if (!ids.has(el)) ids.set(el, 'control-' + ++serial)
      const id = ids.get(el)!
      el.setAttribute('data-tour-control', id)
      const question = el.closest<HTMLElement>('[data-help-question]')
      const declared = el.closest<HTMLElement>('[data-help]')
      const nativeLabel = (el as HTMLInputElement).labels?.[0]
      const isField = el.matches('input,select,textarea')
      const own =
        el.getAttribute('aria-label') ||
        (isField
          ? labelText(nativeLabel || el.closest('label'))
          : (el.textContent || '').trim()) ||
        el.getAttribute('title') ||
        ''
      const name =
        own ||
        question?.dataset.helpQuestion ||
        el.getAttribute('placeholder') ||
        '未命名控件'
      const editorHeading = el
        .closest('section')
        ?.querySelector(':scope > h2')
        ?.textContent?.trim()
      const context =
        question?.dataset.helpQuestion ||
        (editorHeading && /^\d+\./.test(editorHeading) ? editorHeading : '')
      const title = context && own ? `${context} · ${own}` : name
      let text = declared?.dataset.help || fields[name] || ''
      if (!text && question) text = question.dataset.helpText || ''
      if (!text && !isField)
        text = actions.find(([pattern]) => pattern.test(name))?.[1] || ''
      if (!text && el.matches('.fc-event'))
        text = el.matches('.humanos-fixed-event')
          ? '这是固定活动或保护时段，排程会避开此时间；不能拖动修改。'
          : el.matches('.humanos-candidate-event')
            ? '这是待确认草案中的任务工作段，需要确认才会保存。审核时可拖动或拉伸允许编辑的工作段，修改后仍需校验并确认。'
            : '这是已确认计划中的任务工作段；时间到达不代表任务已经完成。在参与者工作台点击任务可查看详情。'
      if (!text && el.matches('summary'))
        text = '展开或收起本区域的详细说明与记录；不会提交或更改数据。'
      if (!text && el.matches('a[href]'))
        text = '打开所选条目的详情或编辑页面；离开前请保存当前尚未提交的修改。'
      if (!text && isField) {
        if (
          el.matches('input[type="checkbox"]') &&
          /周[一二三四五六日天]/.test(name)
        )
          text = /\d{4}-\d{2}-\d{2}/.test(name)
            ? '勾选表示这天有可用时间，取消勾选会清空这天的可用时段；调整后保存整页。'
            : '勾选此活动需要重复发生的星期；仍受当前规划期与生效日期限制。'
        else if (/开始时间|时段开始|结束时间|时段结束/.test(name))
          text =
            '设置这段时间的起止时刻；结束必须晚于开始，且位于当前规划范围内。修改后保存。'
        else if (/选项/.test(name))
          text =
            '每行填写一个参与者可选的选项，选项不能为空或重复；修改后预览并保存。'
        else if (/难度/.test(name))
          text = '按自己的判断填写任务难度，1 最低、10 最高。'
        else if (/预计|时长|分钟/.test(name))
          text =
            '以分钟为单位填写此项所需时长，并核对页面给出的范围。修改后保存。'
        else if (/名称|标题/.test(name))
          text = '为这一项填写容易识别的名称，完成后保存。'
        else if (/原因|说明/.test(name))
          text = '补充这次操作的原因或必要信息，随对应操作一起提交。'
      }
      const documented = !!text
      el.setAttribute(
        'data-tour-help-status',
        documented ? 'documented' : 'fallback',
      )
      if (!text)
        text = '请结合本区域说明操作；如不确定，可以先关闭指引查看页面提示。'
      const input = el as HTMLInputElement
      if (
        isField &&
        el.matches('input[type="number"],input[type="range"]') &&
        (input.min || input.max)
      )
        text += ` 页面允许范围：${input.min || '未设下限'}–${input.max || '未设上限'}${input.step ? `，步长 ${input.step}` : ''}。`
      if (el.matches(':disabled'))
        text += ` 当前控件不可用。${el.getAttribute('title') || '请先处理页面提示的前置事项。'}`
      return { target: 'control:' + id, title, text, documented }
    })
}
