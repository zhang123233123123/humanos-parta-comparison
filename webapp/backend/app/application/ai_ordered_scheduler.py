from copy import deepcopy
from datetime import timedelta
import math

from ..domain.timeline import WeeklySegment, WeeklyTimeAxis
from ..domain.planning.task_order import TaskOrderOutput
from ..domain.planning.task_priority import PLACEMENT_PRIORITY
