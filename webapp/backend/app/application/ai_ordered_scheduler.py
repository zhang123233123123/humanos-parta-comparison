from .interruption_prompt_context import GUIDANCE as INTERRUPTION_GUIDANCE

PROMPT_VERSION = 'ai_segment_order_v11'
MAX_ATTEMPTS = 3
ORDER_PROMPT = INTERRUPTION_GUIDANCE + 'Placement priority: ' + ' -> '.join(PLACEMENT_PRIORITY) + '.\n' + """
Order the execution segments already generated by Python. Return exactly
{"ordered_segment_ids": ["segment_id", ...]}. Include every supplied segment once.
Do not return work amounts, windows, times, deferrals, reasons or other fields.
Python owns segment lengths, chronological placement, rest, grid and validation.
Python locks fixed tasks, allocates ordinary work, then preferred tasks, then flexible tasks.
Preferred and flexible tasks use remaining capacity; do not reserve their windows before ordinary work.
Preserve ordinal order within each task. All segments of hard predecessors must
precede dependent tasks; soft/inferred dependencies are not hard constraints.
Use task_analysis and decision_context to inform order: explicit user preferences,
system-inferred learned behaviors as soft references, task demands, deadlines and interruption costs.
A task selected for this planning period remains eligible even when its deadline falls after this week.
All else equal, place nearer deadlines before later deadlines; preserve explicit priorities and hard dependencies.
Current observations apply only to today's next work, never inferred future state.
recent_behavior contains retrieved recent single-event summaries and their original facts,
including interruption reasons, progress, next steps and remaining amounts. There is no
separate injected interruption history. Use source facts over summary interpretations.
learned_behaviors contains all eligible long-term behavior patterns as persistent background,
not a relevance-selected subset. These are uncertain system observations, not fixed traits.
Do not double count shared sources or interpret missing records as rest, fatigue or preference.
End is not completion. Do not erase unfinished work or change segments based on history.
User selections and hard constraints take precedence over inferred preferences.
Continuous/interleaved preferences guide ordering of the existing full segments.
Concentrated/spread day placement is a Python soft preference, never an output field.
No new parallel work is authorized. Fixed/frozen blocks and protected rest are
preserved by Python. When validation reports an order conflict, revise only the
permutation. Do not invent or omit IDs, change segment work, or expand scope.
"""


class OrderViolation(ValueError):
    def __init__(self, code, **details):
        self.detail = {'type': code, **details}
        super().__init__(code)


def prepare_order_facts(prepared):
    windows = []
    available = WeeklyTimeAxis.subtract(prepared['available'], [
        WeeklySegment(a, b) for a, b in prepared['occupied']])
    for segment in available:
        windows.append({'id': f'w{len(windows)}', 'start_minute': segment.start,
                        'end_minute': segment.end, 'kind': 'available'})
    candidates = []
    for task_id, task in prepared['tasks'].items():
        remaining = max(_remaining_minutes(task) - prepared['allocated'].get(task_id, 0), 0)
        if remaining:
            candidates.append({'task_id': task_id, 'remaining_minutes': remaining,
                               'deadline_minute': _deadline_axis(task, prepared['now'], prepared['week_start']),
                               'hard_predecessors': sorted(prepared['dependencies'].get(task_id, []))})
    segments = []
    for task in candidates:
        left = task['remaining_minutes']
        ordinal = 0
        while left > 0:
            ordinal += 1
            work = min(left, prepared['session_minutes'])
            segments.append({'segment_id': f"segment-{len(segments) + 1}",
                'task_id': task['task_id'], 'ordinal': ordinal, 'work_minutes': work})
            left -= work
    return {'candidate_tasks': candidates, 'segments': segments, 'windows': windows,
            'current_minute': prepared['current_axis'],
            'rest_minutes': prepared['rest_minutes'],
            'grid_minutes': prepared['grid_minutes'],
            'session_limit_minutes': prepared['session_minutes'],
            'week_id': prepared['week_id'], 'now': prepared['now'].isoformat()}


def allocate_order(prepared, facts, raw_order, decision_context, *, _spread=None):
    # Time distribution is a code-owned soft placement preference, not model output.
    if _spread is None:
        baseline = allocate_order(prepared, facts, raw_order, decision_context, _spread=False)
        preferences = prepared.get('profile', {}).get('task_preferences') or {}
        if preferences.get('task_distribution_preference') == 'spread':
            try:
                spread = allocate_order(prepared, facts, raw_order, decision_context, _spread=True)
                if sum(x.get('remaining_minutes', 0) for x in spread['unscheduled_tasks']) <= sum(x.get('remaining_minutes', 0) for x in baseline['unscheduled_tasks']):
                    return spread
            except OrderViolation:
                pass
        return baseline
    order = TaskOrderOutput.model_validate(raw_order).model_dump()
    segments = {s['segment_id']: s for s in facts['segments']}
    ids = order['ordered_segment_ids']
    if len(ids) != len(segments) or len(set(ids)) != len(ids) or set(ids) != set(segments):
        raise OrderViolation('segment_permutation_mismatch', expected=list(segments))
    seen = {}
    predecessors = prepared['dependencies']
    counts = {}
    for segment in segments.values():
        counts[segment['task_id']] = counts.get(segment['task_id'], 0) + 1
    for sid in ids:
        segment = segments[sid]
        task_id = segment['task_id']
        if segment['ordinal'] != seen.get(task_id, 0) + 1:
            raise OrderViolation('segment_order_reversed', segment_id=sid)
        for before in predecessors.get(task_id, []):
            if seen.get(before, 0) < counts.get(before, 0):
                raise OrderViolation('hard_dependency_unsatisfied', task_id=task_id, predecessor=before)
        seen[task_id] = segment['ordinal']
    grid, rest = prepared['grid_minutes'], prepared['rest_minutes']
    candidates = {t['task_id']: t for t in facts['candidate_tasks']}
    blocks = deepcopy(prepared['blocks'])
    occupied = list(prepared['occupied'])
    allocated = dict(prepared['allocated'])
    task_end = dict(prepared['task_end'])
    cursor = prepared['current_axis']
    used_ids = {str(b.get('block_id')) for b in blocks}
    unscheduled = deepcopy(prepared['unscheduled'])
    failed_tasks = set()
    for index, sid in enumerate(ids):
        segment = segments[sid]
        task_id, work = segment['task_id'], segment['work_minutes']
        capacity = work
        deadline = candidates[task_id]['deadline_minute']
        blocked = task_id in failed_tasks or any(
            allocated.get(before, 0) < _remaining_minutes(prepared['all_tasks'][before])
            for before in predecessors.get(task_id, []))
        chosen = None
        earliest = max([cursor] + [task_end[before] + rest for before in predecessors.get(task_id, []) if before in task_end])
        if _spread and task_id in task_end:
            earliest = max(earliest, (task_end[task_id] // 1440 + 1) * 1440)
        if not blocked:
            for window in facts['windows']:
                start = math.ceil(max(earliest, window['start_minute']) / grid) * grid
                while start + capacity <= window['end_minute']:
                    end = start + capacity
                    rest_end = min(end + rest, (start // 1440 + 1) * 1440)
                    if deadline is not None and end > deadline:
                        break
                    if (any(s.start <= start and rest_end <= s.end for s in prepared['available'])
                            and not any(start < b and rest_end > a for a, b in occupied)):
                        chosen = (start, end, rest_end, window)
                        break
                    start += grid
                if chosen:
                    break
        if chosen is None:
            # A deadline missed because of earlier ranked work is repairable by AI;
            # genuinely absent capacity is recorded by code, never AI omission.
            if not blocked and deadline is not None and cursor > prepared['current_axis']:
                if any(math.ceil(max(prepared['current_axis'], w['start_minute']) / grid) * grid + capacity <= min(w['end_minute'], deadline) for w in facts['windows']):
                    raise OrderViolation('deadline_order_conflict', segment_id=sid, task_id=task_id)
            failed_tasks.add(task_id)
            unscheduled.append({'task_id': task_id, 'segment_id': sid, 'remaining_minutes': work,
                'reason': 'dependency_or_prior_segment_unscheduled' if blocked else 'no_feasible_slot',
                'message': 'Code could not place this intact segment within authorized time and constraints.'})
            continue
        start, end, rest_end, window = chosen
        seq = len(blocks) + 1
        block_id = f'{task_id}-ai-order-{seq}'
        while block_id in used_ids:
            seq += 1
            block_id = f'{task_id}-ai-order-{seq}'
        used_ids.add(block_id)
        allocated[task_id] = allocated.get(task_id, 0) + work
        remaining = max(_remaining_minutes(prepared['tasks'][task_id]) - allocated[task_id], 0)
        blocks.append({
            'block_id': block_id, 'task_id': task_id, 'day_index': start // 1440,
            'start': (start % 1440) / 60, 'end': ((end - 1) % 1440 + 1) / 60,
            'start_at': (prepared['week_start'] + timedelta(minutes=start)).isoformat(),
            'end_at': (prepared['week_start'] + timedelta(minutes=end)).isoformat(),
            'week_start_minute': start, 'week_end_minute': end,
            'kind': 'task_session', 'mode': 'execution', 'session_minutes': work,
            'planned_work_minutes': work, 'padding_minutes': capacity - work,
            'total_task_minutes': _remaining_minutes(prepared['tasks'][task_id]),
            'remaining_after_block_minutes': remaining, 'week_id': prepared['week_id'],
            'plan_status': 'proposed', 'scheduler': 'ai_order_python_allocation_v1',
            'constraint_evidence': [f"Code segment {segment['segment_id']}; Python reserved {rest}-minute recovery."],
            'used_buffer': window['kind'] == 'buffer', 'ai_order_step': index, 'segment_id': segment['segment_id'],
            'state_scope': 'weekly_skeleton',
        })
        occupied.append((start, rest_end))
        task_end[task_id] = end
        cursor = rest_end
    from ..domain.planning.activity_rules import place_remaining_tasks
    policy = prepared.get('scope_policy') or {}
    frozen_sources = {str(b.get('source_id')) for b in policy.get('frozen_blocks', [])
                      if b.get('kind') in {'recurring_routine', 'flexible_activity'}}
    remaining_blocks, unplaced_activities = place_remaining_tasks(
        prepared['context'].get('activity_requirements', []), prepared['available'], occupied,
        week_start=prepared['week_start'], now_minute=prepared['current_axis'], grid=grid,
        existing_blocks=blocks, preserved_source_ids=frozen_sources)
    blocks.extend(remaining_blocks)
    blocks.sort(key=lambda b: (b['day_index'], b['start'], str(b.get('block_id'))))
    return {
        'action': 'suggest_plan', 'week_id': prepared['week_id'], 'plan_patch': blocks,
        'candidate_plans': [{'id': 'ai_order', 'label': 'AI segment order', 'plan_patch': blocks,
                             'unscheduled_tasks': unscheduled}],
        'selected_candidate_id': 'ai_order', 'unscheduled_tasks': unscheduled,
        'unscheduled_activities': unplaced_activities,
        'ai_task_analysis': prepared['analysis'], 'ai_task_order': order,
        'personalization': {'authority': 'system_inferred_behavior',
            'available_behavior_ids': [p['id'] for p in decision_context.get('learned_behaviors', {}).get('items', [])],
            'applied_behavior_ids': []},
        'requires_confirmation': True, 'control_mode': 'ai_decided_user_confirmed',
        'explanation': 'AI ordered code-generated segments; Python assigned times and checked constraints.',
        'task_ids': sorted(prepared['all_tasks']),
        'constraint_summary': {**prepared['context'], 'preferred_session_minutes': prepared['session_minutes'],
                               'rest_minutes': prepared['rest_minutes']},
        'scheduler': {'engine': 'ai_order_python_allocation_v1', 'ai_role': 'segment_order_only',
                      'grid_minutes': grid, 'policy_version': PROMPT_VERSION},
        **({'replan_policy': prepared['scope_policy']} if prepared['scope_policy'] else {}),
    }


def generate_ordered_plan(*, profile, tasks, analysis, existing_plan, payload,
                          decision_context, typed_completion, encode, validate):
    prepared = build_deterministic_plan(profile=profile, tasks=tasks, analysis=analysis,
        existing_plan=existing_plan, payload=payload, prepare_only=True)
    prepared['profile'] = profile
    facts = prepare_order_facts(prepared)
    messages = [{'role': 'system', 'content': ORDER_PROMPT}, {'role': 'user', 'content': encode({
        'prompt_version': PROMPT_VERSION, 'decision_context': decision_context,
        'task_analysis': select_fields(analysis, (
            'provider', 'model', 'prompt_version', 'parallel_prompt_version',
            'task_demands', 'task_resource_profiles', 'dependencies',
            'parallel_candidate_pairs', 'parallel_context_pairs',
            'evidence', 'confidence_level',
        )),
        'allocation_facts': facts})}]
    attempts = []
    if not facts['candidate_tasks']:
        # No discretionary work exists; retain fixed/frozen blocks without inventing a ranking.
        result = allocate_order(prepared, facts, {'ordered_segment_ids': []}, decision_context)
        result['validation'] = validate(result)
        from .planning_outcome import is_capacity_draft
        if not result['validation'].get('valid') and not is_capacity_draft(result, result['validation']):
            raise ValueError('现有安排未通过约束校验，请先检查日历。 Existing calendar failed validation.')
        if result.get('unscheduled_activities'):
            result['planning_status'] = 'needs_attention'
        return result
    for attempt in range(MAX_ATTEMPTS):
        raw = typed_completion(messages, TaskOrderOutput, 'task_order', temperature=0.1)
        if not isinstance(raw, dict):
            raise ValueError('AI 排序暂不可用，当前计划未改变。请重试或手动安排。 AI task ordering unavailable; retry or edit manually.')
        try:
            result = allocate_order(prepared, facts, raw, decision_context)
            validation = validate(result)
            from .planning_outcome import is_capacity_draft
            if not validation.get('valid') and not is_capacity_draft(result, validation):
                raise OrderViolation('schedule_validation_failed', validation=validation)
            result['validation'] = validation
            if result.get('unscheduled_tasks') or result.get('unscheduled_activities'):
                result['planning_status'] = 'needs_attention'
            result['ai_order_attempts'] = attempts + [{'attempt': attempt + 1, 'valid': True}]
            return result
        except (ValueError, TypeError, KeyError) as exc:
            detail = exc.detail if isinstance(exc, OrderViolation) else {'type': 'invalid_order_fields', 'message': str(exc)[:2000]}
            attempts.append({'attempt': attempt + 1, 'valid': False, 'violations': detail})
            messages.extend([{'role': 'assistant', 'content': encode(raw)},
                             {'role': 'user', 'content': encode({'repair_required': detail})}])
    raise ValueError('AI 排序经三次校验仍不可执行，当前计划未改变。请调整任务或范围后重试。 AI order could not satisfy constraints after three attempts.')
